#!/usr/bin/env bash
# Regenerate every agent's copy of the rules from the one editable source,
# .claude/rules/*.md.
#
#   scripts/sync-agent-rules.sh           write the copies
#   scripts/sync-agent-rules.sh --check   fail if a copy is missing or stale
#
# Either mode lists files left behind by earlier scaffold versions. This
# script never deletes anything; removing those files is left to a person.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHECK_ONLY=0

if [[ "${1:-}" == "--check" ]]; then
  CHECK_ONLY=1
elif [[ "${1:-}" != "" ]]; then
  echo "Usage: scripts/sync-agent-rules.sh [--check]" >&2
  exit 2
fi

RULE_NAMES=(
  "development-workflow"
  "code-review"
  "coding-standards"
  "tech-stack"
  "sandbox-permissions"
)

# Installed or generated by earlier scaffold versions; no longer used.
RETIRED_FILES=(
  ".claude/rules/python-standards.md"
  ".cursor/rules/python-standards.mdc"
  ".codex/rules/python-standards.md"
  ".codex/rules/claude-python-standards.md"
  ".codex/rules/claude-code-review.md"
  ".codex/rules/claude-development-workflow.md"
  ".codex/rules/claude-tech-stack.md"
  ".codex/rules/claude-sandbox-permissions.md"
)

for name in "${RULE_NAMES[@]}"; do
  if [[ ! -f "$ROOT_DIR/.claude/rules/$name.md" ]]; then
    echo "Missing rule source: .claude/rules/$name.md" >&2
    exit 1
  fi
done

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

write_consolidated_ruleset() {
  local output="$1"
  {
    cat <<'HEADER'
# Consolidated Agent Ruleset

Generated by `scripts/sync-agent-rules.sh` from `.claude/rules/*.md`. Do not edit this file; edit the source and re-run the script.

HEADER
    for name in "${RULE_NAMES[@]}"; do
      cat "$ROOT_DIR/.claude/rules/$name.md"
      printf '\n'
    done
  } > "$output"
}

write_agent_bindings() {
  local output="$1"
  {
    cat <<'HEADER'
# Agent Bindings

Generated by `scripts/sync-agent-rules.sh`.

## Source
- `.claude/rules/*.md` is the only place rules are edited. Claude Code loads these files directly.

## Generated Copies
- `.cursor/rules/*.mdc` for Cursor.
- `.codex/rules/*.md` and `rulesets/CONSOLIDATED_RULESET.md` for Codex and any other agent.

## Managed Rule Names
HEADER
    for name in "${RULE_NAMES[@]}"; do
      printf -- '- `%s`\n' "$name"
    done
  } > "$output"
}

status=0

sync_or_check() {
  local expected="$1"
  local target="$2"
  if [[ $CHECK_ONLY -eq 1 ]]; then
    if [[ ! -f "$ROOT_DIR/$target" ]]; then
      echo "Drift: missing generated file $target" >&2
      status=1
    elif ! cmp -s "$expected" "$ROOT_DIR/$target"; then
      echo "Drift: generated file is stale: $target" >&2
      status=1
    fi
  else
    mkdir -p "$(dirname "$ROOT_DIR/$target")"
    cp "$expected" "$ROOT_DIR/$target"
  fi
}

for name in "${RULE_NAMES[@]}"; do
  sync_or_check "$ROOT_DIR/.claude/rules/$name.md" ".cursor/rules/$name.mdc"
  sync_or_check "$ROOT_DIR/.claude/rules/$name.md" ".codex/rules/$name.md"
done

write_consolidated_ruleset "$TMP_DIR/CONSOLIDATED_RULESET.md"
write_agent_bindings "$TMP_DIR/AGENT_BINDINGS.md"
sync_or_check "$TMP_DIR/CONSOLIDATED_RULESET.md" "rulesets/CONSOLIDATED_RULESET.md"
sync_or_check "$TMP_DIR/AGENT_BINDINGS.md" "rulesets/AGENT_BINDINGS.md"

retired_present=()
for rel in "${RETIRED_FILES[@]}"; do
  if [[ -e "$ROOT_DIR/$rel" ]]; then
    retired_present+=("$rel")
  fi
done

if [[ ${#retired_present[@]} -gt 0 ]]; then
  echo "Retired rule files are still present. They are no longer used and agents may still load them; delete them:" >&2
  for rel in "${retired_present[@]}"; do
    echo "  $rel" >&2
  done
fi

if [[ $status -ne 0 ]]; then
  exit 1
fi

if [[ $CHECK_ONLY -eq 1 ]]; then
  echo "Agent rule copies are in sync with .claude/rules."
else
  echo "Agent rules synced from .claude/rules into .cursor/rules, .codex/rules, and rulesets/."
fi
